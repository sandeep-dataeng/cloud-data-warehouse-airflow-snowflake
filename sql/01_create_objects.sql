CREATE TABLE IF NOT EXISTS STG_CUSTOMER (
    CUSTOMER_ID STRING,
    CUSTOMER_NAME STRING,
    EMAIL STRING,
    CITY STRING,
    UPDATED_AT TIMESTAMP_NTZ,
    BATCH_ID STRING
);

CREATE TABLE IF NOT EXISTS DIM_CUSTOMER (
    CUSTOMER_KEY NUMBER AUTOINCREMENT,
    CUSTOMER_ID STRING,
    CUSTOMER_NAME STRING,
    EMAIL STRING,
    CITY STRING,
    EFFECTIVE_START TIMESTAMP_NTZ,
    EFFECTIVE_END TIMESTAMP_NTZ,
    IS_CURRENT BOOLEAN
);

-- Illustrative SCD Type 2 pattern.
-- Precondition: STG_CUSTOMER contains at most one deterministic row per
-- CUSTOMER_ID for this batch. Validate duplicates before running.
-- Execute in a controlled development environment.
BEGIN TRANSACTION;

UPDATE DIM_CUSTOMER AS d
SET EFFECTIVE_END = CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
    IS_CURRENT = FALSE
FROM STG_CUSTOMER AS s
WHERE d.CUSTOMER_ID = s.CUSTOMER_ID
  AND d.IS_CURRENT = TRUE
  AND (
       NVL(d.CUSTOMER_NAME, '') <> NVL(s.CUSTOMER_NAME, '')
    OR NVL(d.EMAIL, '') <> NVL(s.EMAIL, '')
    OR NVL(d.CITY, '') <> NVL(s.CITY, '')
  );

INSERT INTO DIM_CUSTOMER (
    CUSTOMER_ID, CUSTOMER_NAME, EMAIL, CITY,
    EFFECTIVE_START, EFFECTIVE_END, IS_CURRENT
)
SELECT
    s.CUSTOMER_ID, s.CUSTOMER_NAME, s.EMAIL, s.CITY,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ, NULL, TRUE
FROM STG_CUSTOMER AS s
LEFT JOIN DIM_CUSTOMER AS d
  ON d.CUSTOMER_ID = s.CUSTOMER_ID
 AND d.IS_CURRENT = TRUE
WHERE d.CUSTOMER_ID IS NULL;

COMMIT;
